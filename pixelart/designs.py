def grid_of(art):
    rows = [r for r in art.strip("\n").split("\n")]
    width = max(len(r) for r in rows)
    grid = []
    for r in rows:
        grid.append([None if ch == "." else ("█", ch) for ch in r.ljust(width, ".")])
    return grid


if __name__ == "__main__":
    from PIL import Image
    out = os.path.join(HERE, "out")
    os.makedirs(out, exist_ok=True)
    tiles = []
    for name, art in DESIGNS.items():
        lines = b.encode(grid_of(art), 9, True)
        open(os.path.join(out, name + " - книга.txt"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
        img = b.render(lines, scale=3)
        img.save(os.path.join(out, name + " - превью.png"))
        tiles.append(img)
    cols = 4
    w, h = tiles[0].size
    sheet = Image.new("RGB", (w * cols, h * ((len(tiles) + cols - 1) // cols)), "white")
    for i, t in enumerate(tiles):
        sheet.paste(t, ((i % cols) * w, (i // cols) * h))
    sheet.save(os.path.join(HERE, "pixelart_sheet.png"))
    print(len(tiles))
